const fs = require('fs');
const path = require('path');

const templatesDir = path.resolve(__dirname, '../templates');
const outputFile = path.resolve(__dirname, '../src/lib/registry.generated.ts');

function generateRegistry() {
  if (!fs.existsSync(templatesDir)) {
    console.error('Templates directory not found:', templatesDir);
    return;
  }

  const entries = fs.readdirSync(templatesDir, { withFileTypes: true });
  const slugs = entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((slug) => {
      const hasMeta = fs.existsSync(path.join(templatesDir, slug, 'meta.ts'));
      const hasTemplate = fs.existsSync(path.join(templatesDir, slug, 'Template.tsx'));
      return hasMeta && hasTemplate;
    });

  console.log(`Discovered ${slugs.length} templates: ${slugs.join(', ')}`);

  let imports = `// Auto-generated by scripts/gen-registry.js - DO NOT EDIT MANUALLY\n\n`;
  imports += `import React from 'react';\n`;
  imports += `import { TemplateMeta, TemplateSchema, StyleSettings } from './types';\n\n`;

  slugs.forEach((slug) => {
    const varName = slug.replace(/[^a-zA-Z0-9]/g, '_');
    imports += `import { meta as ${varName}_meta } from '../../templates/${slug}/meta';\n`;
    imports += `import { schema as ${varName}_schema } from '../../templates/${slug}/schema';\n`;
    imports += `import { Template as ${varName}_Component } from '../../templates/${slug}/Template';\n`;
    imports += `import ${varName}_sample from '../../templates/${slug}/sample-data.json';\n\n`;
  });

  let registryDef = `export interface RegisteredTemplate {\n`;
  registryDef += `  meta: TemplateMeta;\n`;
  registryDef += `  schema: TemplateSchema;\n`;
  registryDef += `  sampleData: Record<string, any>;\n`;
  registryDef += `  Component: React.ComponentType<{ data: any; styles?: Partial<StyleSettings> }>;\n`;
  registryDef += `}\n\n`;

  registryDef += `export const templateRegistry: Record<string, RegisteredTemplate> = {\n`;
  slugs.forEach((slug) => {
    const varName = slug.replace(/[^a-zA-Z0-9]/g, '_');
    registryDef += `  '${slug}': {\n`;
    registryDef += `    meta: ${varName}_meta,\n`;
    registryDef += `    schema: ${varName}_schema,\n`;
    registryDef += `    sampleData: ${varName}_sample,\n`;
    registryDef += `    Component: ${varName}_Component,\n`;
    registryDef += `  },\n`;
  });
  registryDef += `};\n\n`;

  registryDef += `export const allTemplates: RegisteredTemplate[] = Object.values(templateRegistry);\n`;

  fs.writeFileSync(outputFile, imports + registryDef, 'utf-8');
  console.log(`Successfully generated registry at: ${outputFile}`);
}

generateRegistry();
